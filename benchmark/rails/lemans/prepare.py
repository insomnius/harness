#!/usr/bin/env python3
"""Prepare matched baseline/design-thinking task variants for Rails Lemans."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
SKILL_SOURCE = ROOT / "plugins/design-thinking/skills/design-thinking"
CORPUS_REVISION = "168d25fae0b9a1df857e9db90440998011fbb350"
COMMENT_GUIDANCE = "Add a code comment only when it explains an important, non-obvious reason. Do not add comments that merely restate what code does."
AGENT_GUIDANCE = f"""## Shared benchmark guidance

Keep changes focused on the requested behavior and follow existing conventions. {COMMENT_GUIDANCE}
"""
VARIANTS = ("baseline", "design-thinking")


def command(args: list[str], *, cwd: Path | None = None) -> str:
    result = subprocess.run(args, cwd=cwd, check=True, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return result.stdout


def hash_tree(root: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(item for item in root.rglob("*") if item.is_file()):
        digest.update(str(path.relative_to(root)).encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def instruction_parts(path: Path) -> tuple[str, str]:
    lines = path.read_text().splitlines()
    markers = [index for index, line in enumerate(lines) if line.strip() == "---"]
    if len(markers) < 2:
        raise ValueError(f"Missing task front matter in {path}")
    return "\n".join(lines[markers[0] + 1 : markers[1]]), "\n".join(lines[markers[1] + 1 :]).strip()


def prepare_patch(base: Path, task_patch: Path, destination: Path, variant: str) -> None:
    with tempfile.TemporaryDirectory(prefix="lemans-task-seed-") as temporary:
        workspace = Path(temporary) / "app"
        shutil.copytree(base, workspace)
        command(["git", "apply", str(task_patch)], cwd=workspace)

        guidance_path = workspace / "AGENTS.md"
        existing_guidance = guidance_path.read_text().rstrip() if guidance_path.is_file() else ""
        guidance_path.write_text(f"{existing_guidance}\n\n{AGENT_GUIDANCE}".lstrip())
        skill_dir = workspace / ".agents/skills/design-thinking"
        shutil.rmtree(skill_dir, ignore_errors=True)
        if variant == "design-thinking":
            shutil.copytree(SKILL_SOURCE, skill_dir)
            command(["git", "add", "-N", "-f", "--", ".agents/skills/design-thinking"], cwd=workspace)
        command(["git", "add", "-N", "-f", "--", "AGENTS.md"], cwd=workspace)
        destination.write_text(command(["git", "diff", "HEAD", "--binary"], cwd=workspace))


def write_bench_config(path: Path, *, base_image: str, model: str) -> None:
    config = f'''# Generated by benchmark/rails/lemans/prepare.py. Keep task data outside this repository.
version: 1

environment:
  backend: docker
  workdir: /app
  profiles:
    fizzy:
      image: {json.dumps(base_image)}
  resources:
    cpus: 2
    memory: 5GB
    storage: 5GB
  build_timeout: 30m
  network:
    mode: none

agent:
  name: miniswen
  model: {json.dumps(model)}
  timeout: 90m
  step_limit: 400
  cost_limit: 60.0
  exec_timeout: 300
  environment:
    network:
      mode: none

verifier:
  timeout: 10m
  command: ruby -Itest -report-lemans /tests/verification_test.rb
  preverify: bin/rails test
  restore:
    - test
    - bin
    - config/environments/test.rb
'''
    path.write_text(config)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", type=Path, required=True, help="Pinned rails/ai-evals checkout outside this repository")
    parser.add_argument("--base-app", type=Path, required=True, help="Clean Fizzy app snapshot extracted from the upstream image")
    parser.add_argument("--output", type=Path, default=Path("/tmp/harness-rails-lemans"))
    parser.add_argument("--tasks", default="ft-card-stalled-quiet-clock,ft-card-drop-settled-landing")
    parser.add_argument("--variants", default=",".join(VARIANTS), help="Comma-separated conditions: baseline,design-thinking")
    parser.add_argument("--model", default="openai/gpt-6-luna#max")
    parser.add_argument("--base-image", default="harness-fizzy-lemans:rails-ai-evals-168d25f")
    args = parser.parse_args()

    corpus = args.corpus.expanduser().resolve()
    base = args.base_app.expanduser().resolve()
    output = args.output.expanduser().resolve()
    if not (corpus / "bench.yml").is_file() or not (base / ".git").is_dir():
        parser.error("--corpus must contain bench.yml and --base-app must be a git checkout")
    if output.exists():
        parser.error(f"Output already exists; choose a fresh path: {output}")
    try:
        corpus.relative_to(ROOT)
    except ValueError:
        pass
    else:
        parser.error("Keep the Rails corpus outside this repository")
    try:
        output.relative_to(ROOT)
    except ValueError:
        pass
    else:
        parser.error("Keep generated Lemans task data outside this repository")

    revision = command(["git", "-C", str(corpus), "rev-parse", "HEAD"]).strip()
    if revision != CORPUS_REVISION:
        parser.error(f"Corpus revision mismatch: expected {CORPUS_REVISION}, found {revision}")
    base_status = command(["git", "status", "--porcelain"], cwd=base)
    if base_status.strip():
        parser.error("--base-app must be a clean snapshot")

    output.mkdir(parents=True)
    (output / "tasks").mkdir()
    task_ids = [item.strip() for item in args.tasks.split(",") if item.strip()]
    variants = [item.strip() for item in args.variants.split(",") if item.strip()]
    if not variants or set(variants) - set(VARIANTS):
        parser.error(f"--variants must contain one or more of: {', '.join(VARIANTS)}")
    for task_id in task_ids:
        source = corpus / "tasks" / task_id
        frontmatter, body = instruction_parts(source / "instruction.md")
        for variant in variants:
            name = f"{task_id}-{variant}"
            task_output = output / "tasks" / name
            task_output.mkdir()
            variant_frontmatter = re.sub(r"(?m)^name:\s*.*$", f"name: {name}", frontmatter, count=1)
            condition_metadata = f"  condition: {variant}\n  source_task: {task_id}"
            if re.search(r"(?m)^metadata:\s*$", variant_frontmatter):
                variant_frontmatter = re.sub(
                    r"(?m)^metadata:\s*$",
                    f"metadata:\n{condition_metadata}",
                    variant_frontmatter,
                    count=1,
                )
            else:
                variant_frontmatter += f"\nmetadata:\n{condition_metadata}"
            if variant == "design-thinking":
                treatment = (
                    "Before editing, read `.agents/skills/design-thinking/SKILL.md` and follow its workflow. "
                    "Use its scripts and project-local design records where they help with this task."
                )
            else:
                treatment = "This evaluation condition has no design-thinking skill files or design history."
            updated_instruction = f"---\n{variant_frontmatter}\n---\n\n{body}\n\n{treatment}\n"
            (task_output / "instruction.md").write_text(updated_instruction)
            prepare_patch(base, source / "environment.patch", task_output / "environment.patch", variant)
            for filename in ("solution.patch", "verification_test.rb"):
                shutil.copy2(source / filename, task_output / filename)

    write_bench_config(output / "bench.yml", base_image=args.base_image, model=args.model)
    manifest = {
        "corpus_revision": revision,
        "skill_sha256": hash_tree(SKILL_SOURCE),
        "base_image": args.base_image,
        "model": args.model,
        "conditions": variants,
        "tasks": task_ids,
        "attempts_recommended": 3,
        "agent": "miniswen",
    }
    (output / "prepared.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"bench": str(output), **manifest}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
